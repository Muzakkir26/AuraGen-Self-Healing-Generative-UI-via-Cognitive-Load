"""
Cross-Team Contract Verification Test (Member-02 Frontend <-> Member-03 Backend)
Validates that telemetry payloads generated by Member-02 strictly satisfy Member-03's API schema.
Contract:
- Mandatory keys: ['mouseSpeed', 'pauseTime', 'rageClicks', 'fieldName', 'userInput']
- Validates contract example: {mouseSpeed: 120, pauseTime: 5, rageClicks: 4} -> score: 85, triggerAI: true
"""

import unittest
from typing import Dict, Any, Tuple

class TeammateContractValidator:
    REQUIRED_KEYS = ["mouseSpeed", "pauseTime", "rageClicks", "fieldName", "userInput"]

    @classmethod
    def validate_payload(cls, data: Any) -> Tuple[bool, str]:
        if not isinstance(data, dict):
            return False, "Request body must be a JSON object dictionary."
        for key in cls.REQUIRED_KEYS:
            if key not in data:
                return False, f"Missing required key: '{key}'. Exact keys required: {', '.join(cls.REQUIRED_KEYS)}"
        if not isinstance(data["mouseSpeed"], (int, float)) or data["mouseSpeed"] < 0:
            return False, "Invalid 'mouseSpeed': must be a non-negative number."
        if not isinstance(data["pauseTime"], (int, float)) or data["pauseTime"] < 0:
            return False, "Invalid 'pauseTime': must be a non-negative number."
        if not isinstance(data["rageClicks"], int) or data["rageClicks"] < 0:
            return False, "Invalid 'rageClicks': must be a non-negative integer."
        if not isinstance(data["fieldName"], str):
            return False, "Invalid 'fieldName': must be a string."
        if not isinstance(data["userInput"], str):
            return False, "Invalid 'userInput': must be a string."
        return True, "Valid payload"

class Member03ScoringReference:
    @staticmethod
    def calculate_score(speed: float, pause: float, rage: int) -> int:
        # Member-03 piecewise formula
        speed_pts = 0 if speed < 20 else (5 if speed < 100 else (10 if speed <= 350 else 15))
        pause_pts = min(35, int(pause) * 7)
        rage_pts = min(40, rage * 10)
        return speed_pts + pause_pts + rage_pts

class TestCrossTeamContract(unittest.TestCase):
    def test_exact_contract_payload_and_score(self):
        # Exact payload from Member-02 / Member-03 contract
        sample = {
            "mouseSpeed": 120,
            "pauseTime": 5,
            "rageClicks": 4,
            "fieldName": "panNumber",
            "userInput": "ABCDE1234F"
        }
        valid, msg = TeammateContractValidator.validate_payload(sample)
        self.assertTrue(valid, msg)
        
        score = Member03ScoringReference.calculate_score(sample["mouseSpeed"], sample["pauseTime"], sample["rageClicks"])
        self.assertEqual(score, 85, "Contract example must yield exactly score: 85")
        self.assertTrue(score >= 70, "Score 85 must trigger AI healing (triggerAI: true)")
        print(f"  [PASS] Teammate Contract: Payload valid, Score: {score}/90, triggerAI: True")

    def test_missing_mandatory_key_rejection(self):
        # Missing 'userInput'
        bad_sample = {
            "mouseSpeed": 50,
            "pauseTime": 2,
            "rageClicks": 1,
            "fieldName": "annualIncome"
        }
        valid, err = TeammateContractValidator.validate_payload(bad_sample)
        self.assertFalse(valid)
        self.assertIn("userInput", err)
        print(f"  [PASS] Contract Enforcement: Caught missing key '{err}'")

    def test_invalid_type_rejection(self):
        # Non-numeric mouseSpeed
        bad_sample = {
            "mouseSpeed": "fast",
            "pauseTime": 2,
            "rageClicks": 1,
            "fieldName": "panNumber",
            "userInput": ""
        }
        valid, err = TeammateContractValidator.validate_payload(bad_sample)
        self.assertFalse(valid)
        self.assertIn("mouseSpeed", err)
        print("  [PASS] Contract Enforcement: Caught invalid data type for 'mouseSpeed'")

if __name__ == "__main__":
    print("=" * 70)
